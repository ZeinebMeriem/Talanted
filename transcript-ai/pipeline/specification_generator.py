"""Project Specification Generator — produces a polished, client-facing PDF.

Creates a "Cahier des Charges" style document that consolidates all pipeline
outputs into a professional project specification:
  - Executive Summary
  - Project Context & Objectives
  - Functional Requirements (numbered, categorized)
  - Non-Functional Requirements
  - System Architecture Overview (with ASCII diagrams rendered cleanly)
  - Data Model & API Design
  - Security & Integration
  - Project Timeline & Team Estimates
  - Risk Assessment
  - Open Items & Next Steps
  - Appendix: System Diagram

Designed to be a middle-ground document that both clients and technical
teams can understand.
"""

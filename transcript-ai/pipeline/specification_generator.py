# ── Page drawing callbacks ────────────────────────────────────────────────────

def _header_footer(canvas, doc, title="Project Specification"):
    """Draw header line and footer on every page."""
    canvas.saveState()
    # Top accent bar
    canvas.setFillColor(colors.HexColor(BRAND["primary"]))
    canvas.rect(0, H - 8 * mm, W, 8 * mm, fill=True, stroke=False)
    canvas.setFillColor(colors.HexColor(BRAND["light"]))
    canvas.setFont("Helvetica-Bold", 8)
    canvas.drawString(20 * mm, H - 6 * mm, title.upper())
    canvas.drawRightString(W - 20 * mm, H - 6 * mm, f"Page {doc.page}")
    # Bottom line
    canvas.setStrokeColor(colors.HexColor(BRAND["border"]))
    canvas.setLineWidth(0.5)
    canvas.line(20 * mm, 14 * mm, W - 20 * mm, 14 * mm)
    canvas.setFillColor(colors.HexColor(BRAND["text_light"]))
    canvas.setFont("Helvetica", 7)
    canvas.drawString(20 * mm, 10 * mm, f"Generated by ScribeAI — {datetime.now().strftime('%B %d, %Y')}")
    canvas.drawRightString(W - 20 * mm, 10 * mm, "Confidential")
    canvas.restoreState()



# ── Table helpers ─────────────────────────────────────────────────────────────

def _std_table_style(header_bg=BRAND["dark"], header_fg=BRAND["light"]):
    """Standard table styling for the specification."""
    return [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(header_bg)),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor(header_fg)),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 9),
        ("FONTSIZE", (0, 1), (-1, -1), 9),
        ("LEADING", (0, 0), (-1, -1), 12),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor(BRAND["border"])),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]


def _zebra_rows(n_data_rows, color="#faf5f0"):
    """Generate alternating row background commands for n data rows."""
    cmds = []
    for i in range(2, n_data_rows + 1, 2):
        cmds.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor(color)))
    return cmds


